def show(chart, height=None):
    """Render with shared axis config: full-length labels, horizontal x labels."""
    if height:
        chart = chart.properties(height=height)
    chart = chart.configure_axis(labelLimit=360, labelFontSize=12, titleFontSize=12).configure_axisX(labelAngle=0)
    st.altair_chart(chart, width="stretch")


def usd(x):
    """Dollar amount safe inside Streamlit markdown ($...$ would render as LaTeX)."""
    return f"\\${x:,.0f}"


def kpi(col, label, value, sub=None, help=None, delta=None, delta_color="normal"):
    col.metric(label, value, delta, help=help, delta_color=delta_color)
    if sub:
        col.caption(sub)


def pct(x, d=1):
    return f"{x:.{d}%}"


def pp(x, d=2):
    return f"{x * 100:+.{d}f}pp"


def fmt_value(v, unit):
    if unit == "proportion":
        return pct(v, 2)
    if unit == "usd_per_user":
        return f"${v:.2f}"
    return f"{v:.3f}"


def fmt_diff(row):
    if row["unit"] == "proportion":
        return f"{pp(row['diff'])} [{row['ci_low']*100:+.2f}, {row['ci_high']*100:+.2f}]"
    return f"{row['diff']:+.3f} [{row['ci_low']:+.3f}, {row['ci_high']:+.3f}]"


