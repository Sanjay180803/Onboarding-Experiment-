    alpha = b.select_slider("Significance level (alpha)", [0.01, 0.025, 0.05, 0.10], DES["alpha"])
    pw = b.select_slider("Power", [0.70, 0.80, 0.85, 0.90, 0.95], DES["power"])
    traffic = a.number_input("Eligible signups per day", 100, 100_000, int(round(DES["daily_signups"])), 100)
    rho = b.slider("CUPED covariate correlation (rho)", 0.0, 0.9, 0.0, 0.05,
                   help=f"Variance falls by rho². This test's best covariate (CUPAC) had rho = {DES['rho_cupac']:.2f}.")
    if baseline + mde >= 1:
        st.error("Baseline + MDE must be below 100%.")
        st.stop()
    out = D.plan(D.PlanInputs(baseline, mde, alpha, pw, traffic, rho))
    c = st.columns(3)
    kpi(c[0], "Users per arm", f"{out['n_per_arm_adjusted']:,}",
        sub=f"{out['n_per_arm'] - out['n_per_arm_adjusted']:,} fewer thanks to CUPED" if rho else "plain z-test")
    kpi(c[1], "Total users", f"{2 * out['n_per_arm_adjusted']:,}")
    kpi(c[2], "Runtime", f"{out['runtime_days']} days",
        sub=f"{out['runtime_days_exact']} days of traffic, rounded up to full weeks")
    mdes = np.linspace(0.0025, min(0.10, 0.99 - baseline), 80)
    curve = D.power_curve(baseline, out["n_per_arm_adjusted"], alpha, mdes)
    ch = alt.Chart(curve).mark_line(color=CONTROL, strokeWidth=2).encode(
        x=alt.X("mde_pp:Q", title="True effect (pp)"), y=alt.Y("power:Q", title="Power", axis=alt.Axis(format="%"),
                                                              scale=alt.Scale(domain=[0, 1])),
        tooltip=[alt.Tooltip("mde_pp:Q", format=".2f", title="effect (pp)"), alt.Tooltip("power:Q", format=".0%")])
    ref = alt.Chart(pd.DataFrame({"y": [pw]})).mark_rule(color=MUTED, strokeDash=[4, 4]).encode(y="y:Q")
    show((ch + ref).properties(title="Power at the planned sample size"), 300)
    st.info(f"At this sample size, D30 retention (baseline {pct(DES['baseline_d30'])}) would need a true effect of about "
            f"{D.power.mde_proportions(DES['baseline_d30'], out['n_per_arm_adjusted'], alpha, pw) * 100:.1f}pp to reach "
            f"{pw:.0%} power, which is why downstream metrics are directional only.")

