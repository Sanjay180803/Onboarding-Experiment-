    st.caption("Plan the next test. Defaults are this experiment's pre-registered design; the math is `abkit.power`, "
               "the same code that produced the preregistration.")
    a, b = st.columns(2)
    baseline = a.number_input("Baseline rate", 0.01, 0.80, float(DES["baseline_activation_7d"]), 0.005,
                              format="%.4f", key="baseline")
