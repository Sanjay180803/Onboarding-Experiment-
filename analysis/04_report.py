"""STEP 4 -- Write the technical report and the one-page decision memo from
results.json / validation.json, so every number in prose is reproducible."""
import json

import pandas as pd

from common import REPORTS, ROOT


def pp(x, d=2):
    return f"{x * 100:+.{d}f}pp"


def pct(x, d=1):
    return f"{x:.{d}%}"


def ci_pp(r, lo="ci_low", hi="ci_high"):
    return f"[{r[lo] * 100:+.2f}, {r[hi] * 100:+.2f}]"


def money(x):
    return f"${x:,.0f}"


def main():
    R = json.loads((REPORTS / "results.json").read_text())
    V = json.loads((REPORTS / "validation.json").read_text())
    D, P, S, I = R["design"], R["primary"], R["secondary"], R["impact"]
    iv, cm, did, g = R["iv"], R["community"], R["did"], R["guardrail_support"]
    sc = I["scenarios"]
    n_tests = 1 + len(S) + 1

    labels = {"onboarded_7d": "Onboarding complete (7d)", "d1_retained": "D1 retention",
              "d7_retained": "D7 retention", "d30_retained": "D30 retention", "paid_30d": "Paid conversion (30d)",
              "revenue_30d": "Revenue / user (30d), bootstrap", "sessions_per_active_day": "Sessions / active day, delta method"}
    sec_rows = []
    for k, lab in labels.items():
        r = S[k]
        is_money = k == "revenue_30d"
        is_ratio = k == "sessions_per_active_day"
        fmt = (lambda v: f"${v:.2f}") if is_money else ((lambda v: f"{v:.3f}") if is_ratio else pct)
        dfmt = (lambda v: f"{v:+.3f}") if (is_money or is_ratio) else pp
        sec_rows.append(f"| {lab} | {fmt(r['control'])} | {fmt(r['treatment'])} | {dfmt(r['diff'])} "
                        f"[{dfmt(r['ci_low'])}, {dfmt(r['ci_high'])}] | {r['p_value']:.3f} | {r['p_holm']:.3f} |")

    seg = pd.DataFrame(R["segments"])
    seg_rows = "\n".join(f"| {s.segment} | {s.n:,} | {pct(s.control)} | {pp(s['diff'])} [{s.ci_low*100:+.2f}, {s.ci_high*100:+.2f}] |"
                         for _, s in seg.iterrows())
    q = pd.DataFrame(R["uplift"]["quintiles"])
    q_rows = "\n".join(f"| Q{int(r.bin)} | {pp(r.pred_cate)} | {pp(r.observed_effect)} [{r.ci_low*100:+.2f}, {r.ci_high*100:+.2f}] |"
                       for _, r in q.iterrows())
    val = pd.DataFrame(V["table"])
    naive = val[val.ci_low.isna()]
    rel_err = (naive.error / naive.truth).abs()
    v_rows = "\n".join(
        f"| {r.estimand} | {r.method} | {r.estimate:+.4f} | "
        + ("—" if pd.isna(r.ci_low) else f"[{r.ci_low:+.4f}, {r.ci_high:+.4f}]")
        + f" | {r.truth:+.4f} | " + ("—" if r.ci_covers_truth is None or pd.isna(r.ci_covers_truth) else ("yes" if r.ci_covers_truth else "**no**")) + " |"
        for r in val.itertuples())

    report = f"""# Technical report: Guided Onboarding Checklist experiment

All numbers are generated by `analysis/02_analyze.py` and `analysis/03_validate.py`. Figures are in `reports/figures/`.

## 1. Design recap (from the pre-experiment cohort)
Baseline 7-day activation was {pct(D['baseline_activation_7d'], 2)}. To detect +{D['mde_abs']*100:.0f}pp at alpha = {D['alpha']} and {D['power']:.0%} power we needed **{D['n_per_arm']:,} users per arm** (simulated power {pct(D['simulated_power'])}), i.e. **{D['runtime_days']} days** at ~{D['daily_signups']:,.0f} signups/day. See `docs/preregistration.md`.

![funnel](figures/01_historical_funnel.png)
![power](figures/03_power_curve.png)

## 2. Trust checks
- **Sample ratio:** {R['srm']['observed'][0]:,} control vs {R['srm']['observed'][1]:,} treatment, chi-square p = {R['srm']['p_value']:.3f}. No SRM.
- **Guardrail, support tickets (7d):** {pct(g['control'], 2)} → {pct(g['treatment'], 2)}, {pp(g['diff'])} {ci_pp(g)}, p = {g['p_value']:.3f}. Significant at 5%, but below the pre-registered +1pp block threshold. See section 9: in this simulation the true effect is zero, so this is a false positive, which is expected roughly once across {n_tests} tests at alpha = 0.05.

## 3. Primary metric: 7-day activation
| | Control | Treatment | Absolute lift [95% CI] | Relative lift [95% CI] | p |
|---|---|---|---|---|---|
| Activation 7d | {pct(P['control'], 2)} | {pct(P['treatment'], 2)} | **{pp(P['diff'])}** {ci_pp(P)} | {pct(P['rel_lift'])} [{pct(P['rel_ci_low'])}, {pct(P['rel_ci_high'])}] | {P['p_value']:.2g} |

**Variance reduction.** CUPED on pre-signup visits (rho = {R['cuped']['corr']:.2f}) cut variance by {pct(R['cuped']['variance_reduction'])}. CUPAC, with a gradient-boosted prediction trained on the historical cohort only, cut it by {pct(R['cupac']['variance_reduction'])}: {pp(R['cupac']['adj_diff'])} [{R['cupac']['adj_ci'][0]*100:+.2f}, {R['cupac']['adj_ci'][1]*100:+.2f}]. The gains are small because new users have little pre-period behavior, which is typical of onboarding tests. For tests on existing users, where prior-period activity is available, the reduction is usually much larger.

## 4. Secondary metrics (Holm-corrected)
| Metric | Control | Treatment | Diff [95% CI] | p | p (Holm) |
|---|---|---|---|---|---|
{chr(10).join(sec_rows)}

![forest](figures/06_metric_forest.png)
![funnel by variant](figures/04_experiment_funnel.png)
![retention](figures/05_retention_by_variant.png)

Onboarding completion moves as expected, since it is the mechanism. Retention, paid conversion and revenue are directionally positive or flat with wide CIs. The design said this would happen: the MDE for D30 retention at this sample size is {D['mde_at_planned_n_d30']*100:.1f}pp, and the observed effects are far smaller. Revenue per user is heavy-tailed (annual vs monthly plans), so its CI comes from a bootstrap. Sessions per active day is a ratio metric whose analysis unit (day) differs from the randomization unit (user), so its CI uses the delta method.

## 5. Sequential testing: why we didn't peek
In 5,000 simulated A/A tests at this traffic, stopping at the first daily p < 0.05 produced a **{pct(R['peeking_sim_aa']['naive_peeking'])} false-positive rate**, compared with {pct(R['peeking_sim_aa']['fixed_horizon'])} for a single look at the end. Always-valid mSPRT p-values held it at {pct(R['peeking_sim_aa']['msprt'])}. The price is power: with a +2.5pp true effect, the fixed-horizon test detects it {pct(R['peeking_sim_ab']['fixed_horizon'], 0)} of the time and mSPRT {pct(R['peeking_sim_ab']['msprt'], 0)} of the time. Applied to the real experiment, mSPRT would first have allowed a stop on **day {R['msprt_on_experiment']['first_day_significant']}** of {D['runtime_days']}.

![peeking](figures/07_peeking.png)

## 6. Noncompliance: effect on users who actually used the checklist
Only {pct(iv['first_stage'])} of treatment users opened the checklist. Randomized assignment serves as an instrument:

| Estimate | Value | Valid? |
|---|---|---|
| ITT (effect of *offering* the checklist) | {pp(iv['itt'])} | Yes, randomized |
| **CACE via IV** (effect of *using* it, for compliers) | **{pp(iv['cace'])}** {ci_pp(iv)} | Yes, under exclusion and monotonicity |
| Openers vs. all control | {pp(iv['per_protocol_naive'])} | No, openers are more motivated |
| Openers vs. non-openers | {pp(iv['as_treated_naive'])} | No, badly confounded |

The naive comparisons overstate the effect by 60–90%. Practical implication: raising the open rate to 80% would lift ITT to about {pp(I['itt_if_80pct_open'])}.

## 7. Observational question: does joining the community *cause* retention?
Community opt-in is self-selected, so joiners and non-joiners differ before they join (max standardized mean difference {cm['max_abs_smd_before']:.2f}).

| Method | D30 retention effect [95% CI] |
|---|---|
| Naive (joiners − non-joiners) | {pp(cm['naive'])} |
| Inverse propensity weighting | {pp(cm['ipw'])} [{cm['ipw_ci'][0]*100:+.2f}, {cm['ipw_ci'][1]*100:+.2f}] |
| AIPW (doubly robust, cross-fitted) | **{pp(cm['aipw'])}** [{cm['aipw_ci'][0]*100:+.2f}, {cm['aipw_ci'][1]*100:+.2f}] |

After weighting, the max SMD is {cm['max_abs_smd_after']:.2f} (good balance). About half of the naive gap was selection. **Sensitivity:** E-value = {cm['e_value']:.2f}. An unmeasured confounder would need a risk ratio of about {cm['e_value']:.1f} with both joining and retention to explain the effect away. This is not proof, so the recommendation is to validate with a randomized encouragement test.

![balance](figures/08_ipw_balance.png)

## 8. Non-randomized rollout: streak reminders (difference-in-differences)
Ops rolled streak reminders out to the 6 strongest of 12 markets in week 12.

| Method | Effect on weekly active rate |
|---|---|
| Naive: treated vs. untreated markets, post period | {pp(did['naive_post_comparison'])} (selection on levels) |
| Naive: treated markets, before vs. after | {pp(did['naive_before_after'])} (confounded by seasonality) |
| **DiD (market and week FE, clustered SE)** | **{pp(did['att'])}** {ci_pp(did)} |

The event-study leads are flat, which supports parallel trends.

![event study](figures/09_event_study.png)

## 9. Heterogeneous effects
| Segment | n | Control activation | Lift [95% CI] |
|---|---|---|---|
{seg_rows}

Cross-fitted T-learner, users grouped by predicted uplift:

| Quintile | Predicted | Observed lift [95% CI] |
|---|---|---|
{q_rows}

![uplift](figures/10_uplift_quintiles.png)

There is directional evidence that low-intent users benefit more. However, the individual-level model's rank correlation with the true CATE is only {V['uplift_rank_corr_with_true_cate']:.2f}: at about 14k users, segment-level heterogeneity is detectable but individual uplift barely is. The web-platform point estimate is negative with a wide CI. With {len(seg)} segment cuts and no pre-registered hypothesis, that is not evidence to exclude web.

## 10. Validation against ground truth (simulation only)
| Estimand | Method | Estimate | 95% CI | Truth | CI covers truth |
|---|---|---|---|---|---|
{v_rows}

Every principled estimator's CI covers the truth. Every naive comparison is off by {rel_err.min():.0%}–{rel_err.max():.0%} of the true effect. The one CI that misses is the guardrail false positive, which is the expected ~5% miss rate showing up once.
"""
    (REPORTS / "report.md").write_text(report)

    memo = f"""# Decision memo: Guided Onboarding Checklist

**Recommendation: Ship to 100% of new users**, with a 5% long-term holdout and a support-ticket monitor.

## What we tested
A guided onboarding checklist, aimed at the funnel's biggest leak (only {pct(D['biggest_funnel_leak']['step_conversion'], 0)} of users who finish onboarding go on to activate). The test ran for {D['runtime_days']} days with {P['n_c'] + P['n_t']:,} new users randomized 50/50. It was pre-registered and powered for +{D['mde_abs']*100:.0f}pp on 7-day activation.

## What we found
1. **Activation rose {pp(P['diff'], 1)}** (from {pct(P['control'])} to {pct(P['treatment'])}, a {pct(P['rel_lift'], 0)} relative lift). 95% CI {ci_pp(P)}, p = {P['p_value']:.1g}. The result held under variance-reduced analysis and passed the sample-ratio check.
2. **For users who actually opened the checklist, the lift is about {pp(iv['cace'], 1)}.** Only {pct(iv['first_stage'], 0)} opened it, so discoverability is the next lever.
3. **Downstream metrics (retention, paid, revenue) are directionally positive but not significant.** This was expected: the test was not sized to detect them.
4. **Support tickets ticked up {pp(g['diff'], 1)}** (p = {g['p_value']:.2f}). This is below our +1pp block threshold. If real, it would cost about {money(I['extra_ticket_cost'])} per year, well under the benefit below.

## Expected impact (annualized, ~{I['annual_signups']:,.0f} signups)
| | CI low | Point | CI high |
|---|---|---|---|
| Additional activated users | {sc['optimistic_low']['incremental_activated']:,.0f} | {sc['optimistic_point']['incremental_activated']:,.0f} | {sc['optimistic_high']['incremental_activated']:,.0f} |
| Additional payers (pessimistic to optimistic link) | {sc['pessimistic_low']['incremental_payers']:,.0f}–{sc['optimistic_low']['incremental_payers']:,.0f} | {sc['pessimistic_point']['incremental_payers']:,.0f}–{sc['optimistic_point']['incremental_payers']:,.0f} | {sc['pessimistic_high']['incremental_payers']:,.0f}–{sc['optimistic_high']['incremental_payers']:,.0f} |
| First-year revenue | {money(sc['pessimistic_low']['revenue'])}–{money(sc['optimistic_low']['revenue'])} | **{money(sc['pessimistic_point']['revenue'])}–{money(sc['optimistic_point']['revenue'])}** | {money(sc['pessimistic_high']['revenue'])}–{money(sc['optimistic_high']['revenue'])} |

*Assumptions:* first-year value of {money(I['ltv_per_payer_assumption'])} per payer, and {money(I['cost_per_ticket_assumption'])} per support ticket. The activation-to-payer link comes from historical data, adjusted for user mix ({I['adjusted_link_upper']:.3f} payers per activated user), and is treated as an upper bound because motivated users both activate and pay. The pessimistic case uses half of it. The raw, unadjusted gap ({I['raw_activation_paid_gap']:.3f}) would overstate impact.

## Next steps
1. **Ship to all platforms**, keeping a **5% holdout for 90 days** to measure paid conversion and revenue directly. That is the only way to replace the assumption above with a measured number.
2. **Run a follow-up test on checklist discoverability.** Raising opens from {pct(iv['first_stage'], 0)} to 80% is worth about {pp(I['itt_if_80pct_open'] - iv['itt'], 1)} more activation.
3. **Tag and monitor support tickets** from checklist users for 4 weeks. Revisit if the rate rises by 1pp or more.
4. **Do not exclude web users yet.** The negative web estimate is one of {len(seg)} unplanned segment cuts with a wide CI. Low-intent users may benefit most; test a tailored checklist for them.
5. **Separately, community features look causally valuable** (about {pp(cm['aipw'], 1)} D30 retention after adjusting for self-selection, versus {pp(cm['naive'], 1)} naive). Confirm with a randomized encouragement test before investing.
"""
    (ROOT / "docs" / "decision_memo.md").write_text(memo)
    print("wrote reports/report.md and docs/decision_memo.md")


if __name__ == "__main__":
    main()
